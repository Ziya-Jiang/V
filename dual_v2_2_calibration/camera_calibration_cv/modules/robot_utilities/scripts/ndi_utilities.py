import numpy
import pandas as pd
from enum import Enum
from scipy.spatial.transform import Rotation as ScipyR

from .robot import Robot

class RobotType(Enum):
    CUARM_V2_2: 0
    NACHI_MZ04: 1
    
class NdiToolType(Enum):
    TOOL_8700339 = 0
    TOOL_8700449 = 0

def nachi_MZ04_tool_ball_height(): 
    """ Thickness between ndi tool back plane and center of silver ball, on Nachi MZ04 """
    return [-22.77, 0, 0] #22.77 = 14+8.77

def cuarm_v2_2_tool_ball_height():
    """ Thickness between ndi tool back plane and center of silver ball, on Cuarm v2.2 """
    return [-13.77, 0, 0] #13.77 = 5+8.77

def tool_8700449_center_shift():
    """
    Tool 8700449 center is defined on one of the silver ball by default. This function 
    return a vector from the defualt center to the middle of tool plane.
    """
    A, B, C, D, E, F = 55.55, 50.01, 64.33, 76.54, 82.98, 89.01
    a = numpy.arccos((B**2+E**2-A**2)/(2*B*E))
    e = numpy.arccos((B**2+F**2-C**2)/(2*B*F))
    b = numpy.pi - a - e
    AE = B*numpy.sin(a)/numpy.sin(b)
    return [0, 0, AE]

def tool_8700339_center_shift(): 
    """
    Tool 8700339 center is defined on one of the silver ball by default. This function 
    return a vector from the defualt center to the middle of tool plane.
    """
    A, B, C, D, E, F = 50.00, 60.00, 65.00, 55.00, 72.91, 88.00
    a = numpy.arccos((B**2+E**2-A**2)/(2*B*E))
    e = numpy.arccos((B**2+F**2-C**2)/(2*B*F))
    b = numpy.pi - a - e
    AE = B*numpy.sin(a)/numpy.sin(b)
    return [0, 0, AE]

def read_raw_ndi_file(path, state=None, columns=[]):
    """
    Given a raw ndi file path, return specified columns with state == "OK". 
    Raw ndi file is generated by official NDI software.
    Args:
        path: path to a raw ndi csv 
        state: state name in csv
        columns: column names in csv used for output
    Returns:
        dataframe of specified columns with state == "OK"
    """
    if not state:
        state = 'State'
    if not columns:
        columns = ['Tx', 'Ty', 'Tz', 'Qx', 'Qy', 'Qz', 'Q0']
    df = pd.read_csv(path, low_memory=False)
    df1 = df[df[state] == 'OK']
    df2 = df1[columns]
    return df2.to_numpy()

def apply_robot_and_tool_offset(data, tool:NdiToolType, robot:RobotType):
    """
    Apply robot offset and tool offset to data
    Args:
        data: (nx6) numpy array, where n is data size. Row are formed by position 
            vector and axis-angle vector
        tool: tool offset,support "8700339" and "8700449"
        robot: robot offset, support "Cuarm_v2_2", "Nachi_MZ04"
    Returns:
        data: data with applied offset
    """
    #Add ball offset
    origin_offset = numpy.zeros(3)
    if robot == RobotType.CUARM_V2_2:
        origin_offset += numpy.array(cuarm_v2_2_tool_ball_height())
    elif robot == RobotType.NACHI_MZ04:
        origin_offset += numpy.array(nachi_MZ04_tool_ball_height())
    
    #Transfer points to tool center
    if tool == NdiToolType.TOOL_8700449:
        origin_offset += numpy.array(tool_8700449_center_shift())
    elif tool == NdiToolType.TOOL_8700339:
        origin_offset += numpy.array(tool_8700339_center_shift())
        
    for i in range(len(data)):
        R = ScipyR.from_rotvec(data[i,3:]).as_matrix()
        data[i,:3] += R@origin_offset
    return data

def apply_data_specified_offset(data, pos_offset=[0,0,0], ori_offset=[0,0,0]):
    """
    Apply data specified position and orientation offset
    Args:
        data: numpy data with row in (x,y,z,rx,ry,rz) format, where (rx,ry,rz) is angle axis
        pos_offset: position offset
        ori_offset: orientation offset
    Returns:
        res: data with applied offsets
    """
    #Transform from quaternion to rotation angle
    n, l = data.shape[:2]
    R = numpy.eye(3)
    if any(ori_offset):
        Rx = Robot.Rx(ori_offset[0])
        Ry = Robot.Ry(ori_offset[1])
        Rz = Robot.Rz(ori_offset[2])
        R= Rx@Ry@Rz
        
    res = numpy.zeros(data.shape)
    for cycle in range(n):
        for i in range(l):
            R1 = ScipyR.from_rotvec(data[cycle][i,3:]).as_matrix()
            R2 = R1@R
            res[cycle,i,:3] = data[cycle,i,:3] if not any(pos_offset) else data[cycle,i,:3]+R2@pos_offset
            axis_angle = ScipyR.from_matrix(R2).as_rotvec() #Return in Rad.
            res[cycle,i,3:] = axis_angle
    return res

def apply_data_specified_ori_offset(data, ori_offset):
    R = numpy.eye(3)
    if any(ori_offset):
        Rx = Robot.Rx(ori_offset[0])
        Ry = Robot.Ry(ori_offset[1])
        Rz = Robot.Rz(ori_offset[2])
        R = Rx@Ry@Rz
    res = data.copy()
    for p in res:
        R1 = ScipyR.from_rotvec(p[3:]).as_matrix()
        R2 = R1@R
        p[3:] = ScipyR.from_matrix(R2).as_rotvec()
    return res